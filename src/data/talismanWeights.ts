export type ImportanceLevel = keyof typeof IMPORTANCE

/** 武器種によらない重要度（効果の有無は別途 weapons.ts で判定する） */
export function importanceOf(skill: string, weapon: Weapon): ImportanceLevel {
  const w = BY_WEAPON[weapon]
  if (w.core?.includes(skill) || CORE_ALL.includes(skill)) return 'core'
  if (w.sub?.includes(skill) || SUB_ALL.includes(skill)) return 'sub'
  return 'utility'
}

